export function serializeCookies(cookies, format, sourceUrl = "") {
  if (format === "cookie-header") return cookies.map(c => `${c.name}=${c.value}`).join("; ");
  if (format === "netscape") return ["# Netscape HTTP Cookie File", "# Generated by Cookie Brother"].concat(cookies.map(c => `${c.httpOnly ? "#HttpOnly_" : ""}${c.domain}\t${c.hostOnly ? "FALSE" : "TRUE"}\t${c.path || "/"}\t${c.secure ? "TRUE" : "FALSE"}\t${c.session ? "0" : Math.floor(c.expirationDate || 0)}\t${c.name}\t${c.value}`)).join("\n");
  const clean = cookies.map(({ frame, ...cookie }) => cookie);
  if (format === "json") return JSON.stringify(clean.map(c => {
    const session = c.session === true || c.expirationDate == null;
    const item = {
      domain: c.domain, hostOnly: c.hostOnly ?? !String(c.domain || "").startsWith("."),
      httpOnly: Boolean(c.httpOnly), name: c.name, path: c.path || "/",
      sameSite: c.sameSite && c.sameSite !== "unspecified" ? c.sameSite : null,
      secure: Boolean(c.secure), session, storeId: c.storeId || "0", value: c.value ?? ""
    };
    if (!session && Number.isFinite(Number(c.expirationDate))) item.expirationDate = Number(c.expirationDate);
    if (c.partitionKey) item.partitionKey = c.partitionKey;
    return item;
  }), null, 2);
  return JSON.stringify({ format: "cookie-brother", version: 1, exportedAt: new Date().toISOString(), source: { url: sourceUrl, browser: "Chromium" }, cookies: clean }, null, 2);
}
